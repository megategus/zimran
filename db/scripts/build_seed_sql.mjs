// Writes db/migrations/0002_local.sql and 0003_models.sql (schema + data) from db/seed/*.json.
// Run: node db/scripts/build_seed_sql.mjs. Edit the JSON, not the SQL.
import { readFileSync, writeFileSync } from 'node:fs';

const read = (f) => JSON.parse(readFileSync(new URL(`../seed/${f}`, import.meta.url), 'utf8'));
const write = (f, sql) => writeFileSync(new URL(`../migrations/${f}`, import.meta.url), sql);

const lit = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'object') return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replaceAll("'", "''")}'`;
};
const insert = (table, cols, rows) => rows.length
  ? `insert into ${table} (${cols.join(', ')}) values\n${rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n')};\n`
  : '';
const HEAD = '-- Generated by db/scripts/build_seed_sql.mjs from db/seed. Do not edit by hand.\n\n';

const shops = read('shops_austin.json');
const prices = read('shop_prices_austin.json');
write('0002_local.sql', `${HEAD}create table shops (
  id uuid primary key default gen_random_uuid(),
  osm_id text unique not null,
  name text not null,
  address text,
  zip text not null,
  lat float8 not null,
  lon float8 not null,
  website text,
  phone text,
  kind text not null check (kind in ('dealer', 'independent', 'chain', 'tire')),
  source text not null,
  as_of date not null
);

create table shop_prices (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references shops (id) on delete cascade,
  job_key text not null,
  price_cents int not null check (price_cents >= 0),
  includes text,
  source_url text not null,
  as_of date not null,
  is_special bool not null default false
);

create index shops_zip_idx on shops (zip);
create index shop_prices_job_idx on shop_prices (job_key);
alter table shops enable row level security;
alter table shop_prices enable row level security;

create view job_price_stats with (security_invoker = true) as
select s.zip, p.job_key, count(*)::int as n,
  min(p.price_cents) as min_cents,
  (percentile_cont(0.5) within group (order by p.price_cents))::int as median_cents,
  max(p.price_cents) as max_cents
from shop_prices p join shops s on s.id = p.shop_id
group by s.zip, p.job_key;

${insert('shops', ['osm_id', 'name', 'address', 'zip', 'lat', 'lon', 'website', 'phone', 'kind', 'source', 'as_of'], shops)}
insert into shop_prices (shop_id, job_key, price_cents, includes, source_url, as_of, is_special)
select s.id, v.job_key, v.price_cents, v.includes, v.source_url, v.as_of::date, v.is_special
from (values
${prices.map((p) => `  (${[p.shop_osm_id, p.job_key, p.price_cents, p.includes, p.source_url, p.as_of, p.is_special].map(lit).join(', ')})`).join(',\n')}
) as v (osm_id, job_key, price_cents, includes, source_url, as_of, is_special)
join shops s on s.osm_id = v.osm_id;
`);

const m = read('models.json');
